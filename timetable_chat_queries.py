"""Compositional, source-grounded answers to multi-part timetable questions.

This layer does not guess faculty assignments, ask a model to invent timetable
facts, or modify scheduled sessions. Every count, day and time is derived from
the *selected* timetable rows and the accompanying workbook group hierarchy.
"""
from __future__ import annotations

import re
from collections import defaultdict

import timetable_assistant as facts

DAY_ORDER = ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')


def _n(v):
    return facts.norm(v)


def _unique_sessions(rows):
    """Aggregate CSV period rows so a two-period practical is one session."""
    return facts._merge_sessions(rows)


def _day(row):
    return _n(row.get('day')).upper()


def _period(row):
    return facts.int_value(row.get('period'))


def _weekly_load(rows, *, count_sessions=False):
    """By-person (display-name), by-day counted from actual selected CSV."""
    details = defaultdict(lambda: defaultdict(set))
    for row in rows:
        teacher = _n(row.get('faculty_name'))
        day = _day(row)
        if not teacher or not day:
            continue
        sid = _n(row.get('session_id'))
        # Session identifiers are generated by the solver. Fall back to a stable
        # per-period key for incomplete sample rows, not a made-up course count.
        item = (sid if sid else (_n(row.get('course_id')), _n(row.get('group_id')), _period(row))) if count_sessions else _period(row)
        details[teacher][day].add(item)
    return {teacher: {day: len(keys) for day, keys in days.items()}
            for teacher, days in details.items()}


def _display_teacher(name):
    """Make an obviously truncated source qualifier readable, never alter IDs.

    Some imported faculty cells contain names such as 'Surname (DMAC' with a
    missing closing parenthesis. This only changes presentation, never the
    identity key used for counts or source lookups.
    """
    return re.sub(r'\s*\([^()]*$', '', name).strip() or name


def _workload_threshold(q):
    """Return (comparison, bound) for explicit numeric workload filtering."""
    patterns = (
        (r'\b(?:at most|no more than)\s+(\d+)\b', 'le'),
        (r'\b(?:at least|no fewer than)\s+(\d+)\b', 'ge'),
        (r'\b(?:more than|greater than|over|above|exceeding|exceeds|exceed)\s+(\d+)\b', 'gt'),
        (r'\b(?:fewer than|less than|under|below)\s+(\d+)\b', 'lt'),
    )
    for pattern, op in patterns:
        found = re.search(pattern, q)
        if found:
            return op, int(found.group(1))
    return None


def _load_answer(question, rows, teacher=None, *, teaching_days=None):
    q = facts.normalized(question)
    class_metric = bool(re.search(r'\b(classes|sessions|lectures)\b', q)) and not bool(
        re.search(r'\b(teaching periods?|hours?|contact hours?)\b', q))
    stats = _weekly_load(rows, count_sessions=class_metric)
    if not stats:
        return 'No scheduled faculty workload data is available for this timetable.'
    units = 'scheduled sessions' if class_metric else 'teaching periods'
    threshold = _workload_threshold(q)
    if not teacher and threshold:
        op, bound = threshold
        comparisons = {
            'gt': lambda n: n > bound,
            'lt': lambda n: n < bound,
            'ge': lambda n: n >= bound,
            'le': lambda n: n <= bound,
        }
        selected = sorted(
            ((person, sum(days.values())) for person, days in stats.items()
             if comparisons[op](sum(days.values()))),
            key=lambda item: (-item[1], item[0].casefold()),
        )
        descriptions = {'gt': f'more than {bound}',
                        'lt': f'fewer than {bound}',
                        'ge': f'at least {bound}',
                        'le': f'at most {bound}'}
        if not selected:
            return (f'**No scheduled teachers** have {descriptions[op]} {units} '
                    'in the selected timetable.')
        return (f'**{len(selected)} scheduled teacher(s) have {descriptions[op]} '
                f'{units}:**\n\n'
                + '\n'.join(f'- **{_display_teacher(person)}** — {count} {units}'
                            for person, count in selected)
                + '\n\nCounts come from the selected timetable; '
                  'faculty with no scheduled classes are not included.')
    rank = re.search(r'\b(highest|most|busiest|heaviest|lowest|least|fewest|lightest)\b', q)
    if teacher is None and not rank:
        return None
    if teacher is None:
        value = min if re.search(r'\b(lowest|least|fewest|lightest)\b', q) else max
        total = value(sum(day.values()) for day in stats.values())
        people = sorted(t for t, days in stats.items() if sum(days.values()) == total)
    else:
        if teacher not in stats:
            return f'No scheduled classes found for **{teacher}** in the selected timetable.'
        people = [teacher]
        total = sum(stats[teacher].values())
    name = ', '.join(_display_teacher(person) for person in people)
    text = f'**{name}** {"have" if len(people)>1 else "has"} **{total} {units}** this week.'
    if teacher is None and re.search(r'\b(lowest|least|fewest|lightest)\b', q):
        text += ' (Among teachers with at least one scheduled class.)'
    if re.search(r'\b(distribut\w*|breakdown|day by day|daily|across the week|each day|per day|weekdays?)\b', q):
        for person in people:
            daily = stats[person]
            calendar = teaching_days or DAY_ORDER[:5]
            detail = ', '.join(f'{facts.DAY_NAMES.get(day,day)} {daily.get(day,0)}'
                               for day in calendar)
            text += f'\n\n**{_display_teacher(person)} — daily distribution ({units}):**\n\n{detail}.'
    if class_metric:
        periods = _weekly_load(rows, count_sessions=False)
        if len(people) == 1:
            text += f'\n\nThese sessions occupy **{sum(periods[people[0]].values())} teaching periods** (a two-period practical counts as one session).'
    else:
        sessions = _weekly_load(rows, count_sessions=True)
        if len(people) == 1:
            text += f'\n\n**{sum(sessions[people[0]].values())} distinct teaching sessions**; each practical period is counted in the teaching-period total.'
    return text


def _schedule_lines(rows):
    merged = rows
    result = []
    for r in merged:
        day = facts.DAY_NAMES.get(_day(r), _day(r))
        start = _n(r.get('start_time'))
        end = _n(r.get('end_time'))
        period = _n(r.get('display_period') or r.get('period'))
        time = f' ({start}–{end})' if start and end else ''
        name = _n(r.get('course_name'))
        course = _n(r.get('course_id'))
        group = _n(r.get('group_id'))
        kind = _n(r.get('kind')).replace('_', ' ').title()
        faculty = _n(r.get('faculty_name'))
        room = _n(r.get('room_id'))
        sid = _n(r.get('session_id'))
        result.append(f'- **{day} P{period}**{time} — **{course}** {name}; '
                      f'{kind}; {group}; {faculty}; room {room}; session `{sid}`')
    return result


def course_sessions(rows, course, *, group=None, day=None, kind=None):
    """Current original placements for course, optionally scoped to section/day."""
    selected = [r for r in rows if _n(r.get('course_id')).casefold() == course.casefold()
                and (not day or _day(r) == day)
                and (not kind or _n(r.get('kind')).upper() == kind.upper())]
    if group:
        selected = [r for r in selected if _n(r.get('group_id')) == group or
                    _n(r.get('group_id')).startswith(group+'__')]
    return _unique_sessions(selected)


def course_schedule_answer(rows, course, *, group=None, day=None, kind=None):
    found = course_sessions(rows, course, group=group, day=day, kind=kind)
    if not found:
        return f'No scheduled sessions for **{course}**' + (f' on {facts.DAY_NAMES.get(day,day)}' if day else '') + ' in this selected timetable.'
    who = f' / {group}' if group else ''
    dates = sorted({_day(r) for r in found}, key=lambda d: DAY_ORDER.index(d) if d in DAY_ORDER else 99)
    names = ', '.join(facts.DAY_NAMES.get(d,d) for d in dates)
    lines = _schedule_lines(found)
    return (f'**{course}{who} is scheduled on {names}: {len(found)} distinct session(s).**'
            '\n\n' + '\n'.join(lines))


def teacher_courses_and_times(teacher, rows):
    selected = [r for r in rows if _n(r.get('faculty_name')) == teacher]
    if not selected:
        return f'No scheduled classes found for **{teacher}**.'
    sessions = _unique_sessions(selected)
    by_course = defaultdict(list)
    titles = {}
    for r in sessions:
        code = _n(r.get('course_id'))
        titles[code] = _n(r.get('course_name'))
        by_course[code].append(r)
    blocks = [f'**{teacher} teaches {len(by_course)} courses. Here are the scheduled times:**']
    for code in sorted(by_course):
        course_lines = [f'**{code} — {titles[code]}**']
        for r in by_course[code]:
            day = facts.DAY_NAMES.get(_day(r), _day(r))
            period = _n(r.get('display_period') or r.get('period'))
            start, end = _n(r.get('start_time')), _n(r.get('end_time'))
            time = f' ({start}–{end})' if start and end else ''
            course_lines.append(f'- {day} P{period}{time} · {_n(r.get("group_id"))}'
                                + (f' · {_n(r.get("room_id"))}' if _n(r.get('room_id')) else ''))
        blocks.append('\n'.join(course_lines))
    return '\n\n'.join(blocks)


def answer_multi_question(question, rows, data, ent):
    """Answer explicitly combined requirements before single-intent legacy code."""
    q = facts.normalized(question)
    teacher, course, group, day = (ent.get(k) for k in ('teacher','course','group','day'))
    calendar = tuple(sorted({_day(slot) for slot in data.get('Time_Slots', []) if _day(slot)},
                            key=lambda d: DAY_ORDER.index(d) if d in DAY_ORDER else 99)) or DAY_ORDER[:5]
    # Count *sessions* for classes, versus occupied teaching periods for hours.
    if re.search(r'\b(teachers?|faculty|professors?|lecturers?|staff|workload)\b', q) and \
            _workload_threshold(q) and \
            re.search(r'\b(classes|sessions|workload|teaching|periods|hours)\b', q):
        return _load_answer(question, rows, teaching_days=calendar)
    if re.search(r'\b(teachers?|faculty|professors?|lecturers?|staff|workload)\b', q) and \
            re.search(r'\b(highest|most|busiest|heaviest|lowest|least|fewest|lightest)\b', q) and \
            re.search(r'\b(classes|sessions|workload|teaching|periods|hours)\b', q):
        return _load_answer(question, rows, teaching_days=calendar)
    if teacher and re.search(r'\b(workload|load|teaching periods|classes)\b',q) and \
            re.search(r'\b(distribut\w*|breakdown|day by day|daily|across the week|each day|per day)\b', q):
        return _load_answer(question, rows, teacher=teacher, teaching_days=calendar)
    if teacher and re.search(r'\b(sections?|groups?|batches?)\b', q) and day and \
            re.search(r'\b(which of|of those|also|and which|all sections|entire week|throughout the week)\b', q):
        groups = {_n(g.get('group_id')):g for g in data.get('Student_Groups', [])}
        all_sections = facts._teacher_section_directory(teacher, rows, groups)
        daily_sections = facts._teacher_section_directory(teacher, rows, groups, day=day)
        return '**All scheduled sections:**\n\n' + all_sections + '\n\n**On ' + facts.DAY_NAMES.get(day,day) + ':**\n\n' + daily_sections
    if teacher and re.search(r'\b(subjects?|courses?|modules?)\b', q) and \
            re.search(r'\b(at what time|what times?|which times?|when|what day|which days?|schedule|timings?)\b', q):
        return teacher_courses_and_times(teacher, rows)
    if course and day and ent.get('follow') and re.search(
            r'\b(what days?|which days?|days when|scheduled|timetable|schedule|when is)\b',
            facts.normalized(ent.get('memory', {}).get('topic_question') or
                             ent.get('memory', {}).get('last_user',''))):
        return course_schedule_answer(rows, course, group=group, day=day)
    if course and re.search(r'\b(what days?|which days?|give days|list days|days when|when is|when are|\bscheduled\b|timetable|schedule)\b', q) and \
            not re.search(r'\b(move|shift|reschedul|swap|change to|transfer)\b', q):
        return course_schedule_answer(rows, course, group=group, day=day)
    return None
